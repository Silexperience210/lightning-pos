//! Police 5×7 monochrome (Adafruit GFX) pour le POS.
//! Chaque glyphe = 5 octets (une colonne, 7 bits significatifs, bit 0 = haut).

/// Rend un caractère dans le framebuffer (couleur donnée). Retourne la largeur.
pub fn draw_char(
    fb: &mut [u16],
    w: usize,
    c: char,
    x: usize,
    y: usize,
    color: u16,
) -> usize {
    let glyph = glyph(c);
    for col in 0..5 {
        let bits = glyph[col];
        for row in 0..7 {
            if bits & (1 << row) != 0 {
                let px = x + col;
                let py = y + row;
                if px < w && py * w + px < fb.len() {
                    fb[py * w + px] = color;
                }
            }
        }
    }
    6 // largeur (5 + 1 espace)
}

/// Largeur d'une chaîne en pixels.
pub fn text_width(s: &str) -> usize {
    s.chars().count() * 6
}

/// Rend un caractère à l'échelle `scale` (chaque pixel = bloc scale×scale).
pub fn draw_char_scaled(
    fb: &mut [u16],
    w: usize,
    c: char,
    x: usize,
    y: usize,
    scale: usize,
    color: u16,
) -> usize {
    let glyph = glyph(c);
    for col in 0..5 {
        let bits = glyph[col];
        for row in 0..7 {
            if bits & (1 << row) != 0 {
                for dy in 0..scale {
                    for dx in 0..scale {
                        let px = x + col * scale + dx;
                        let py = y + row * scale + dy;
                        if px < w && py * w + px < fb.len() {
                            fb[py * w + px] = color;
                        }
                    }
                }
            }
        }
    }
    6 * scale
}

/// Largeur d'une chaîne à l'échelle `scale`.
pub fn text_width_scaled(s: &str, scale: usize) -> usize {
    s.chars().count() * 6 * scale
}

